"""### 6. Production Inference Pipeline (MLOps Readiness)

To bridge the gap between model training and production deployment (FastAPI backend), we must ensure that any incoming raw data (e.g., a JSON payload representing a single student) undergoes the exact same preprocessing (dummy encoding, column alignment, scaling) as our training set.

We will define a `StudentAtRiskPipeline` class that wraps the scaling and prediction processes into a unified object, and save it as an artifact.
"""

class StudentAtRiskPipeline:
    def __init__(self, model, scaler, feature_columns, training_categorical_defaults):
        self.model = model
        self.scaler = scaler
        self.feature_columns = feature_columns
        self.training_categorical_defaults = training_categorical_defaults

    def preprocess(self, raw_data_df):
        """
        Transforms a raw pandas DataFrame containing any subset of raw features
        into the properly encoded and scaled feature matrix.
        """
        df_input = raw_data_df.copy()

        # 1. Fill missing categorical or behavioral values with reasonable defaults
        for col, default in self.training_categorical_defaults.items():
            if col not in df_input.columns:
                df_input[col] = default

        # 2. Get dummies using pandas matching training format
        df_encoded = pd.get_dummies(df_input)

        # 3. Reindex columns to match the exact training features structure (filling missing with 0)
        df_aligned = df_encoded.reindex(columns=self.feature_columns, fill_value=0)

        # 4. Scale using the fitted scaler
        scaled_features = self.scaler.transform(df_aligned)
        return scaled_features

    def predict(self, raw_data_df):
        scaled_x = self.preprocess(raw_data_df)
        return self.model.predict(scaled_x)

    def predict_proba(self, raw_data_df):
        scaled_x = self.preprocess(raw_data_df)
        return self.model.predict_proba(scaled_x)

# Prepare pipeline dependencies
categorical_defaults = {
    'schoolsup': 'no', 'famsup': 'no', 'paid': 'no', 'activities': 'no',
    'nursery': 'yes', 'higher': 'yes', 'internet': 'yes', 'romantic': 'no',
    'course': 'math'
}

# Instantiate the pipeline wrapper
pipeline = StudentAtRiskPipeline(
    model=best_model,
    scaler=scaler,
    feature_columns=list(X.columns),
    training_categorical_defaults=categorical_defaults
)

# Save the unified pipeline artifact in relative models directory
with open('models/at_risk_pipeline.pkl', 'wb') as f:
    pickle.dump(pipeline, f)

print("Unified production pipeline successfully saved to 'models/at_risk_pipeline.pkl'!")

